-- =============================================================
-- V1__init_llm_agent_readonly.sql
--
-- Создаёт read-only роль для LLM-агента с доступом на чтение
-- ко всем схемам во всех базах данных кластера — текущим и
-- будущим — без необходимости перечислять схемы вручную.
--
-- После этого файла llm_agent:
--   - может подключиться к любой БД в кластере
--   - может выполнять SELECT по любой таблице/view/sequence
--     в любой схеме, включая те, что появятся позже
--   - не может INSERT/UPDATE/DELETE/CREATE/DROP/TRUNCATE
--   - не может создавать роли, БД или объекты
-- =============================================================

-- -------------------------------------------------------------
-- 1. РОЛЬ (пользователь БД)
--
-- LOGIN — может подключаться к БД.
-- NOCREATEDB, NOCREATEROLE — не может создавать БД и роли.
-- NOSUPERUSER, NOBYPASSRLS — явное отсутствие привилегий.
--
-- Пароль лучше подставлять через переменную окружения /
-- секрет-менеджер, а не хранить в файле миграции.
-- -------------------------------------------------------------
DO $$
    BEGIN
        IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'llm_agent') THEN
            CREATE ROLE llm_agent
                LOGIN
                PASSWORD 'llm_agent_password'
                NOCREATEDB
                NOCREATEROLE
                NOSUPERUSER
                NOBYPASSRLS
                CONNECTION LIMIT 5;
        END IF;
    END
$$;

-- -------------------------------------------------------------
-- 2. READ-ONLY НА ВСЁ, ВО ВСЕХ СХЕМАХ ТЕКУЩЕЙ БД
--
-- pg_read_all_data — предопределённая роль PostgreSQL (14+).
-- Членство в ней автоматически даёт:
--   - USAGE на все схемы
--   - SELECT на все таблицы, view, sequences
-- включая объекты, которые будут созданы ПОЗЖЕ — без
-- ALTER DEFAULT PRIVILEGES и без перечисления схем вручную.
--
-- Это членство в роли — оно проверяется динамически при каждом
-- подключении, поэтому распространяется на любую БД в кластере,
-- в том числе на базы, которые ещё не существуют на момент
-- выполнения этого файла.
-- -------------------------------------------------------------
GRANT pg_read_all_data TO llm_agent;

-- -------------------------------------------------------------
-- 3. ЯВНЫЙ ЗАПРЕТ НА ИЗМЕНЯЮЩИЕ ОПЕРАЦИИ И СОЗДАНИЕ ОБЪЕКТОВ
--
-- pg_read_all_data сама по себе не даёт прав на запись, но этот
-- блок фиксирует намерение явно и защищает от случайного
-- GRANT ALL / GRANT CREATE в будущем.
-- -------------------------------------------------------------
REVOKE ALL ON SCHEMA public FROM llm_agent;